import { execFileSync } from 'node:child_process';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { newProject, makeClip, addTrack } from '../app/model.mjs';
import { buildRender } from '../lib/render.mjs';
const dir=path.resolve('test-results/effects');await fs.mkdir(dir,{recursive:true});
const ffmpeg=process.env.FFMPEG_PATH || path.resolve('tools/ffmpeg.exe');
const ff=args=>execFileSync(ffmpeg,['-hide_banner','-loglevel','error','-y',...args],{windowsHide:true,maxBuffer:20*1024**2});
const asset=(id,filter)=>{const file=path.join(dir,id+'.png');ff(['-f','lavfi','-i',filter,'-frames:v','1',file]);return{id,name:id,kind:'image',width:320,height:180,path:file,duration:2,hasAudio:false};};
const blue=asset('blue','color=c=0x163c72:s=320x180'), green=asset('green','color=c=0x00ff00:s=320x180,drawbox=x=120:y=45:w=80:h=90:color=red:t=fill');
const bands=asset('bands','color=c=red:s=320x180,drawbox=x=160:y=0:w=160:h=180:color=0x00ff00:t=fill');
const assets=[blue,green,bands];
const render=(name,clips,tracks)=>{const p=newProject();p.width=1280;p.height=720;p.clips=clips;if(tracks)p.tracks=tracks; const file=path.join(dir,name+'.mp4');ff(buildRender(p,assets,file,[],''));return file;};
const pixels=(file,t)=>ff(['-ss',String(t),'-i',file,'-frames:v','1','-vf','scale=320:180','-pix_fmt','rgb24','-f','rawvideo','pipe:1']);
const at=(buf,x,y)=>[...buf.subarray((y*320+x)*3,(y*320+x)*3+3)];
const clip=a=>({...makeClip(a,'v1'),duration:2});
const p=newProject(), top=addTrack(p,'video');
const motion=render('key-motion',[clip(blue),{...clip(green),track:top.id,scale:.5,keyEnabled:true,keySimilarity:.2,keyBlend:.05,visualFadeIn:.5,keyframes:{x:[{time:0,value:-.25},{time:2,value:.25}],scale:[{time:0,value:.4},{time:2,value:.6}],opacity:[{time:0,value:1},{time:2,value:1}]}}],p.tracks);
const start=pixels(motion,0), mid=pixels(motion,1), end=pixels(motion,1.5);
assert.ok(at(start,80,90)[2]>at(start,80,90)[0],'fade begins transparent');
assert.ok(at(mid,160,90)[0]>180,'red foreground retained');
assert.ok(at(mid,210,90)[2]>at(mid,210,90)[1],'green is transparent over blue');
assert.ok(at(end,200,90)[0]>180,'position keyframe advances');
const graded=render('graded',[{...clip(blue),exposure:1,contrast:1.2,warmth:.2,saturation:0}]);
const gray=at(pixels(graded,1),160,90); assert.ok(Math.max(...gray)-Math.min(...gray)<6,'saturation zero exports grayscale');
const cropped=render('cropped',[{...clip(bands),cropLeft:.5}]);
const crop=at(pixels(cropped,1),160,90); assert.ok(crop[1]>200 && crop[0]<30,'crop selects right half');
console.log(JSON.stringify({ok:true,checks:['dynamic track order','green-screen alpha','fade','animated position/scale/opacity','grading','crop'],dir}));
